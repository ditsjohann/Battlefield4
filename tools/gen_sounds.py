#!/usr/bin/env python3
"""Procedural sound synthesis for WARFRONT.

Every sound in the mod is generated by this script from noise, oscillators and
envelopes, so the audio is 100% original and license-free. Re-run it to tweak:

    python3 tools/gen_sounds.py

Requires numpy and an ffmpeg build with libvorbis (writes .ogg files).
"""
import os
import subprocess
import tempfile
import wave

import numpy as np

SR = 44100
OUT = os.path.join(os.path.dirname(__file__), "..", "src", "main", "resources", "assets", "warfront", "sounds")
rng = np.random.default_rng(1337)


def t(dur):
    return np.arange(int(SR * dur)) / SR


def noise(dur):
    return rng.uniform(-1, 1, int(SR * dur))


def env_exp(dur, decay, attack=0.0005):
    x = t(dur)
    e = np.exp(-x / decay)
    a = np.clip(x / max(attack, 1e-6), 0, 1)
    return e * a


def lowpass(x, cutoff):
    # one-pole low pass, applied twice for a 12 dB/oct slope
    a = np.exp(-2 * np.pi * cutoff / SR)
    for _ in range(2):
        y = np.zeros_like(x)
        acc = 0.0
        for i in range(len(x)):
            acc = (1 - a) * x[i] + a * acc
            y[i] = acc
        x = y
    return x


def lowpass_fast(x, cutoff):
    # FFT brick-ish lowpass with soft knee (fast for long buffers)
    n = len(x)
    f = np.fft.rfftfreq(n, 1 / SR)
    X = np.fft.rfft(x)
    X *= 1 / (1 + (f / cutoff) ** 4)
    return np.fft.irfft(X, n)


def highpass_fast(x, cutoff):
    n = len(x)
    f = np.fft.rfftfreq(n, 1 / SR)
    X = np.fft.rfft(x)
    X *= 1 / (1 + (cutoff / np.maximum(f, 1)) ** 4)
    return np.fft.irfft(X, n)


def bandpass_fast(x, lo, hi):
    return highpass_fast(lowpass_fast(x, hi), lo)


def sine(freq, dur, sweep_to=None):
    x = t(dur)
    if sweep_to is None:
        return np.sin(2 * np.pi * freq * x)
    f = np.linspace(freq, sweep_to, len(x))
    return np.sin(2 * np.pi * np.cumsum(f) / SR)


def reverb(x, room=0.35, decay=0.45, taps=6):
    out = np.copy(x)
    for i in range(1, taps + 1):
        d = int(SR * room * i / taps * (0.8 + 0.4 * rng.random()))
        g = decay ** i
        out[d:] += x[: len(x) - d] * g * (0.7 + 0.3 * rng.random())
    return out


def pad(x, dur):
    n = int(SR * dur)
    if len(x) >= n:
        return x[:n]
    return np.concatenate([x, np.zeros(n - len(x))])


def mix(*parts):
    n = max(len(p) for p in parts)
    out = np.zeros(n)
    for p in parts:
        out[: len(p)] += p
    return out


def shift(x, sec):
    return np.concatenate([np.zeros(int(SR * sec)), x])


def norm(x, peak=0.92):
    m = np.max(np.abs(x)) or 1
    return x / m * peak


def soft_clip(x, drive=1.5):
    return np.tanh(x * drive) / np.tanh(drive)


def write(name, x, peak=0.92):
    x = norm(x, peak)
    # fade out the last 5ms to avoid clicks
    f = min(len(x), int(SR * 0.005))
    x[-f:] *= np.linspace(1, 0, f)
    pcm = (x * 32767).astype(np.int16)
    os.makedirs(OUT, exist_ok=True)
    with tempfile.NamedTemporaryFile(suffix=".wav", delete=False) as tmp:
        with wave.open(tmp.name, "wb") as w:
            w.setnchannels(1)
            w.setsampwidth(2)
            w.setframerate(SR)
            w.writeframes(pcm.tobytes())
        path = os.path.join(OUT, name + ".ogg")
        subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", tmp.name, "-c:a", "libvorbis", "-q:a", "5", path], check=True)
        os.unlink(tmp.name)
    print("wrote", name)


# ---------------------------------------------------------------- gunshots
def gunshot(body_hz, crack_hz, decay, tail, punch=1.0, room=0.3, dur=0.9, metal=0.0):
    """Layered gunshot: supersonic crack + muzzle blast body + low punch + room tail."""
    crack = highpass_fast(noise(0.03), crack_hz) * env_exp(0.03, 0.004)
    body = lowpass_fast(noise(dur), body_hz) * env_exp(dur, decay)
    thump = sine(95 * punch, 0.25, 40) * env_exp(0.25, 0.05) * 1.6
    mech = np.zeros(1)
    if metal > 0:
        mech = shift(bandpass_fast(noise(0.05), 2500, 6000) * env_exp(0.05, 0.01) * metal, 0.045)
    x = mix(crack * 0.9, body * 1.3, thump * punch, mech)
    x = soft_clip(x, 2.2)
    x = reverb(x, room=room, decay=tail)
    return pad(x, dur)


def distant(x, cutoff=900):
    y = lowpass_fast(x, cutoff)
    y = reverb(y, room=0.6, decay=0.55, taps=8)
    return y


def gen_guns():
    guns = {
        # name: (body_hz, crack_hz, decay, tail, punch, room, metal)
        "rifle_shot": (2600, 3500, 0.06, 0.42, 1.0, 0.28, 0.25),
        "carbine_shot": (3200, 4000, 0.045, 0.38, 0.8, 0.22, 0.3),
        "lmg_shot": (2000, 3000, 0.075, 0.48, 1.25, 0.32, 0.2),
        "sniper_shot": (1700, 3000, 0.11, 0.6, 1.6, 0.5, 0.0),
        "pistol_shot": (3500, 4500, 0.035, 0.32, 0.6, 0.18, 0.35),
        "shotgun_shot": (1500, 2500, 0.1, 0.5, 1.5, 0.35, 0.1),
    }
    for name, (b, c, d, tail, p, r, m) in guns.items():
        for v in range(3):
            # each variant re-rolls the noise and nudges the body/tail so automatic fire never loops audibly
            j = 1 + (v - 1) * 0.06
            x = gunshot(b * j, c, d * (2 - j), tail, p, r, metal=m)
            suffix = "" if v == 0 else f"_v{v + 1}"
            write(name + suffix, x)
            write(name + "_far" + suffix, distant(x, 700 if "sniper" in name else 1000), peak=0.7)
    # suppressed: mostly mechanical + small puff
    puff = lowpass_fast(noise(0.2), 1800) * env_exp(0.2, 0.02)
    mech = shift(bandpass_fast(noise(0.06), 2000, 7000) * env_exp(0.06, 0.012) * 0.8, 0.01)
    write("suppressed_shot", mix(puff, mech))


def gen_mech():
    def click(freq_lo, freq_hi, dec, amp=1.0, dur=0.08):
        return bandpass_fast(noise(dur), freq_lo, freq_hi) * env_exp(dur, dec) * amp

    def ring(f, dur, dec, amp=0.4):
        return sine(f, dur) * env_exp(dur, dec) * amp

    # magazine out: slide + clack
    mag_out = mix(click(800, 3000, 0.03, 0.6, 0.12), shift(click(1500, 5000, 0.01, 1.0), 0.09), shift(ring(1900, 0.2, 0.04), 0.09))
    write("reload_mag_out", pad(mag_out, 0.35))
    mag_in = mix(click(600, 2500, 0.02, 0.5, 0.1), shift(click(1200, 6000, 0.008, 1.2), 0.07), shift(ring(2300, 0.2, 0.03, 0.5), 0.07))
    write("reload_mag_in", pad(mag_in, 0.35))
    bolt = mix(click(1500, 6000, 0.01, 1.0), shift(click(900, 4000, 0.03, 0.6, 0.12), 0.05), shift(click(1500, 7000, 0.008, 1.1), 0.18), shift(ring(3100, 0.15, 0.02, 0.4), 0.18))
    write("reload_bolt", pad(bolt, 0.4))
    write("dry_fire", pad(mix(click(2000, 8000, 0.004, 1.0, 0.03), ring(4200, 0.05, 0.01, 0.3)), 0.12))
    write("fire_mode", pad(mix(click(2500, 8000, 0.003, 1.0, 0.02), shift(click(2500, 8000, 0.003, 0.7, 0.02), 0.04)), 0.12))
    # pin pull for grenade
    pin = mix(ring(3400, 0.25, 0.06, 0.5), ring(5100, 0.2, 0.04, 0.3), click(3000, 9000, 0.005, 0.8, 0.03))
    write("grenade_pin", pad(pin, 0.3))
    # c4 arm beep
    beep = sine(2200, 0.09) * env_exp(0.09, 0.05)
    write("c4_beep", pad(beep, 0.12))
    # repair tool: buzzing arc
    x = t(0.6)
    buzz = np.sign(np.sin(2 * np.pi * 120 * x)) * 0.3 + noise(0.6) * 0.5
    buzz = bandpass_fast(buzz, 300, 4000) * (0.7 + 0.3 * np.sin(2 * np.pi * 9 * x))
    write("repair_loop", buzz)
    # defib charge + zap
    charge = sine(400, 0.6, 3200) * np.linspace(0.1, 0.8, int(SR * 0.6))
    zap = highpass_fast(noise(0.25), 800) * env_exp(0.25, 0.05) * 1.4
    write("defib", mix(charge, shift(zap, 0.6)))
    # bag drop: soft thud with zipper rustle
    write("bag_drop", pad(mix(lowpass_fast(noise(0.2), 400) * env_exp(0.2, 0.03) * 1.5, shift(bandpass_fast(noise(0.15), 2000, 6000) * env_exp(0.15, 0.05) * 0.4, 0.03)), 0.3))
    # resupply chime
    write("resupply", pad(mix(click(1500, 5000, 0.02, 0.6, 0.1), shift(ring(1320, 0.3, 0.08, 0.5), 0.02)), 0.35))


def gen_feedback():
    # hitmarker: short crisp tick
    hit = bandpass_fast(noise(0.04), 2500, 9000) * env_exp(0.04, 0.006)
    write("hitmarker", pad(mix(hit, sine(3800, 0.04) * env_exp(0.04, 0.008) * 0.4), 0.06))
    # headshot: metallic "dink"
    dink = mix(sine(2900, 0.35) * env_exp(0.35, 0.07), sine(4350, 0.3) * env_exp(0.3, 0.05) * 0.6, sine(6100, 0.2) * env_exp(0.2, 0.03) * 0.3)
    write("headshot", pad(mix(dink, hit * 0.6), 0.4))
    # kill confirm: low thunk + tick
    kill = mix(sine(220, 0.2, 140) * env_exp(0.2, 0.05), hit, shift(hit * 0.6, 0.06))
    write("kill_confirm", pad(kill, 0.25))
    # bullet near miss: whip-crack + whizz
    whiz = bandpass_fast(noise(0.22), 1200, 7000) * np.concatenate([np.linspace(0, 1, int(SR * 0.08)), np.linspace(1, 0, int(SR * 0.14))])
    crack = highpass_fast(noise(0.012), 3000) * env_exp(0.012, 0.002) * 2
    write("bullet_crack", pad(mix(crack, whiz * 0.7), 0.3))
    for v in (2, 3):
        whiz = bandpass_fast(noise(0.22), 900 + v * 300, 6500 + v * 400) * np.concatenate([np.linspace(0, 1, int(SR * (0.05 + v * 0.02))), np.linspace(1, 0, int(SR * (0.17 - v * 0.02)))])
        write(f"bullet_crack_v{v}", pad(mix(highpass_fast(noise(0.012), 3000) * env_exp(0.012, 0.002) * 2, whiz * 0.7), 0.3))
        write(f"bullet_impact_v{v}", pad(mix(bandpass_fast(noise(0.12), 600 + v * 200, 5000 + v * 500) * env_exp(0.12, 0.012 + v * 0.003),
                                             lowpass_fast(noise(0.1), 450) * env_exp(0.1, 0.02) * 0.6), 0.15))
    # spent casing hitting the ground: bright brass tink
    for v, f0 in ((1, 4200), (2, 3700), (3, 4800)):
        t2 = mix(sine(f0, 0.18) * env_exp(0.18, 0.03) * 0.5, sine(f0 * 1.52, 0.12) * env_exp(0.12, 0.02) * 0.3,
                 shift(sine(f0 * 0.9, 0.1) * env_exp(0.1, 0.02) * 0.25, 0.05))
        write("casing" if v == 1 else f"casing_v{v}", pad(t2, 0.22))
    # breathing: held breath (sharp inhale) and the release
    inh = bandpass_fast(noise(0.45), 500, 3800) * np.concatenate([np.linspace(0, 1, int(SR * 0.3)), np.linspace(1, 0, int(SR * 0.45) - int(SR * 0.3))]) * 0.35
    write("breath_in", pad(inh, 0.5), peak=0.5)
    exh = bandpass_fast(noise(0.7), 300, 2400) * env_exp(0.7, 0.25, attack=0.04) * 0.4
    write("breath_out", pad(exh, 0.75), peak=0.55)
    # magazine running dry: light rattle of the last rounds
    rattle = np.zeros(int(SR * 0.12))
    for k in range(4):
        c = bandpass_fast(noise(0.02), 3000, 9000) * env_exp(0.02, 0.003) * (0.8 - k * 0.15)
        st = int(k * 0.022 * SR)
        rattle[st:st + len(c)] += c[:len(rattle) - st]
    write("ammo_low", pad(mix(rattle, sine(5200, 0.06) * env_exp(0.06, 0.01) * 0.2), 0.14))
    # bullet impact on block: dusty chip
    write("bullet_impact", pad(mix(bandpass_fast(noise(0.12), 800, 6000) * env_exp(0.12, 0.015), lowpass_fast(noise(0.1), 500) * env_exp(0.1, 0.02) * 0.6), 0.15))
    # ricochet whine
    ric = sine(3400, 0.5, 1800) * env_exp(0.5, 0.15) * 0.6
    write("ricochet", pad(mix(ric, bandpass_fast(noise(0.03), 2000, 8000) * env_exp(0.03, 0.005)), 0.5))
    # glass break
    shards = np.zeros(int(SR * 0.6))
    for _ in range(18):
        f = rng.uniform(2500, 7500)
        s = sine(f, 0.25) * env_exp(0.25, rng.uniform(0.02, 0.07)) * rng.uniform(0.2, 0.6)
        st = int(rng.uniform(0, 0.25) * SR)
        shards[st : st + len(s)] += s[: len(shards) - st]
    write("glass_shatter", mix(highpass_fast(noise(0.3), 2000) * env_exp(0.3, 0.06), shards))
    # score ping (ui): two-note rising blip
    p = mix(sine(1046, 0.09) * env_exp(0.09, 0.05), shift(sine(1568, 0.14) * env_exp(0.14, 0.07), 0.07))
    write("score_ping", pad(p, 0.25))
    # flag captured: triumphant triad sweep
    tri = mix(*(shift(sine(f, 0.6) * env_exp(0.6, 0.25) * 0.5, i * 0.09) for i, f in enumerate([523, 659, 784, 1046])))
    write("flag_captured", pad(tri, 1.0))
    # flag lost: descending minor
    lost = mix(*(shift(sine(f, 0.6) * env_exp(0.6, 0.25) * 0.5, i * 0.12) for i, f in enumerate([622, 523, 415, 311])))
    write("flag_lost", pad(lost, 1.0))
    # capture tick (while capturing)
    write("capture_tick", pad(sine(880, 0.06) * env_exp(0.06, 0.02), 0.08))
    # low ticket warning: pulsing alarm
    x = t(1.2)
    alarm = np.sin(2 * np.pi * (600 + 200 * (np.sin(2 * np.pi * 2.5 * x) > 0)) * x) * 0.5
    write("ticket_warning", alarm * np.linspace(1, 0.6, len(x)))
    # deploy whoosh
    write("deploy", pad(bandpass_fast(noise(0.8), 300, 3000) * np.sin(np.linspace(0, np.pi, int(SR * 0.8))) ** 2, 0.8))
    # spot ping
    write("spot", pad(mix(sine(1760, 0.1) * env_exp(0.1, 0.04), shift(sine(1760, 0.1) * env_exp(0.1, 0.04) * 0.6, 0.08)), 0.25))
    # victory / defeat stingers
    vic = mix(*(shift(sine(f, 1.6) * env_exp(1.6, 0.6) * 0.4 + sine(f * 2, 1.6) * env_exp(1.6, 0.4) * 0.1, i * 0.18) for i, f in enumerate([392, 523, 659, 784])))
    write("victory", pad(reverb(vic, 0.4, 0.4), 2.6))
    dfe = mix(*(shift(sine(f, 1.8) * env_exp(1.8, 0.7) * 0.4, i * 0.3) for i, f in enumerate([392, 349, 311, 262])))
    write("defeat", pad(reverb(dfe, 0.4, 0.4), 3.0))


def gen_explosions():
    def boom(dur, low, decay, crack_amp=0.8, sub=55):
        body = lowpass_fast(noise(dur), low) * env_exp(dur, decay)
        crack = highpass_fast(noise(0.08), 1500) * env_exp(0.08, 0.015) * crack_amp
        subw = sine(sub, dur, 25) * env_exp(dur, decay * 1.3) * 1.5
        debris = np.zeros(int(SR * dur))
        for _ in range(30):
            s = bandpass_fast(noise(0.05), 600, 4000) * env_exp(0.05, 0.01) * rng.uniform(0.05, 0.25)
            st = int(rng.uniform(0.15, dur * 0.8) * SR)
            debris[st : st + len(s)] += s[: len(debris) - st]
        x = soft_clip(mix(body * 1.5, crack, subw, debris), 2.0)
        return reverb(x, room=0.5, decay=0.5, taps=8)

    write("explosion", boom(2.4, 900, 0.35))
    write("explosion_v2", boom(2.6, 800, 0.4))
    write("explosion_v3", boom(2.2, 1000, 0.3))
    write("grenade_explode_v2", boom(1.6, 1300, 0.24, 1.0, 64))
    write("grenade_explode_v3", boom(1.5, 1500, 0.2, 0.9, 76))
    write("explosion_far", distant(boom(2.4, 900, 0.35), 350), peak=0.75)
    write("grenade_explode", boom(1.6, 1400, 0.22, 1.0, 70))
    write("tank_cannon", mix(gunshot(900, 2000, 0.2, 0.6, 2.4, 0.6, dur=2.0), shift(sine(40, 1.5, 22) * env_exp(1.5, 0.4), 0.0)))
    # rocket launch: pop + roaring motor burn
    pop = lowpass_fast(noise(0.2), 1500) * env_exp(0.2, 0.04) * 1.2
    roar = bandpass_fast(noise(1.4), 200, 2500) * env_exp(1.4, 0.5)
    write("rocket_launch", mix(pop, roar * 0.8))
    # rocket in flight (loopable hiss)
    write("rocket_loop", bandpass_fast(noise(1.0), 400, 3500) * 0.6)
    # tower alarm (klaxon)
    x = t(2.4)
    klax = np.sign(np.sin(2 * np.pi * 330 * x)) * 0.35 + np.sin(2 * np.pi * 495 * x) * 0.3
    klax *= (np.sin(2 * np.pi * 1.25 * x) > -0.2).astype(float)
    write("tower_alarm", lowpass_fast(klax, 2500))
    # tower collapse: long rumble with crashes
    dur = 6.0
    rumble = lowpass_fast(noise(dur), 220) * np.concatenate([np.linspace(0.2, 1, int(SR * 1.5)), np.ones(int(SR * 2.5)), np.linspace(1, 0, int(SR * 2.0))])
    crashes = np.zeros(int(SR * dur))
    for _ in range(26):
        c = boom(0.8, rng.uniform(500, 1500), 0.12, 0.6, rng.uniform(40, 80)) * rng.uniform(0.15, 0.5)
        st = int(rng.uniform(0.2, dur - 1.0) * SR)
        crashes[st : st + len(c)] += c[: len(crashes) - st]
    groan = sine(60, dur, 35) * 0.3 * np.sin(np.linspace(0, np.pi, int(SR * dur)))
    write("tower_collapse", mix(rumble * 2, crashes, groan))


def gen_vehicle():
    # tank engine loop: diesel rumble with track clatter (2s loop)
    dur = 2.0
    x = t(dur)
    f0 = 32
    eng = sum(np.sin(2 * np.pi * f0 * k * x + rng.random() * 6) / k for k in range(1, 9))
    eng *= 0.7 + 0.3 * np.sin(2 * np.pi * f0 / 2 * x)
    clatter = np.zeros(len(x))
    for i in range(int(dur * 14)):
        s = bandpass_fast(noise(0.03), 800, 3500) * env_exp(0.03, 0.006) * 0.25
        st = int(i / 14 * SR)
        clatter[st : st + len(s)] += s[: len(x) - st]
    y = lowpass_fast(eng, 600) * 0.8 + clatter + lowpass_fast(noise(dur), 300) * 0.3
    write("tank_engine", y, peak=0.8)
    # turret traverse whine
    write("turret_traverse", bandpass_fast(sine(180, 1.0) + noise(1.0) * 0.2, 100, 1500) * 0.6)
    # tank hit: metal clang
    clang = mix(*(sine(f, 0.9) * env_exp(0.9, d) * a for f, d, a in [(310, 0.3, 0.6), (523, 0.2, 0.5), (1210, 0.12, 0.3), (2100, 0.06, 0.2)]))
    write("vehicle_hit", mix(clang, highpass_fast(noise(0.05), 2000) * env_exp(0.05, 0.01)))
    # vehicle destroyed alarm beep (in-cabin warning)
    beep = np.concatenate([sine(1400, 0.12) * 0.6, np.zeros(int(SR * 0.08))] * 3)
    write("vehicle_warning", beep)


if __name__ == "__main__":
    gen_guns()
    gen_mech()
    gen_feedback()
    gen_explosions()
    gen_vehicle()
